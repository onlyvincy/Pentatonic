function buildPluckedGuitarWav(bpm: number, cleanliness: number, durationSec = 6): Blob {
  const sampleRate = 22050;
  const totalSamples = sampleRate * durationSec;
  const samples = new Float32Array(totalSamples);

  const scaleFreqs = [220, 261.63, 293.66, 329.63, 392.0, 440.0, 523.25, 587.33, 659.25];
  const pattern = [0, 1, 2, 3, 1, 2, 3, 4, 2, 3, 4, 5, 3, 4, 5, 6, 7, 6, 5, 4, 5, 4, 3, 2];

  const noteIntervalSec = 60 / bpm / 2;
  const noteLenSamples = Math.floor(noteIntervalSec * sampleRate * 1.4);

  let noteIdx = 0;
  for (let tSec = 0.05; tSec < durationSec - 0.2; tSec += noteIntervalSec) {
    const freq = scaleFreqs[pattern[noteIdx % pattern.length]];
    const jitterSamples =
      cleanliness <= 3 ? Math.floor((Math.sin(noteIdx * 2.7) * 0.022) * sampleRate) : 0;
    const startSample = Math.max(0, Math.floor(tSec * sampleRate) + jitterSamples);
    const amp = cleanliness >= 4 ? 0.34 : 0.28 + (noteIdx % 2 === 0 ? 0.07 : -0.06);

    for (let i = 0; i < noteLenSamples && startSample + i < totalSamples; i++) {
      const localT = i / sampleRate;
      const env = Math.exp(-localT * (cleanliness >= 4 ? 7.5 : 9.5)) * Math.min(1, i / 40);
      const fundamental = Math.sin(2 * Math.PI * freq * localT);
      const harmonic2 = 0.45 * Math.sin(2 * Math.PI * freq * 2 * localT) * Math.exp(-localT * 6);
      const harmonic3 = 0.22 * Math.sin(2 * Math.PI * freq * 3 * localT) * Math.exp(-localT * 10);
      const buzz =
        cleanliness <= 3 ? 0.06 * Math.sin(2 * Math.PI * freq * 5.3 * localT) * Math.exp(-localT * 24) : 0;
      samples[startSample + i] += amp * env * (fundamental + harmonic2 + harmonic3 + buzz);
    }
    noteIdx++;
  }

  const buffer = new ArrayBuffer(44 + totalSamples * 2);
  const view = new DataView(buffer);
  const writeString = (offset: number, str: string) => {
    for (let i = 0; i < str.length; i++) {
      view.setUint8(offset + i, str.charCodeAt(i));
    }
  };

  writeString(0, 'RIFF');
  view.setUint32(4, 36 + totalSamples * 2, true);
  writeString(8, 'WAVE');
  writeString(12, 'fmt ');
  view.setUint32(16, 16, true);
  view.setUint16(20, 1, true);
  view.setUint16(22, 1, true);
  view.setUint32(24, sampleRate, true);
  view.setUint32(28, sampleRate * 2, true);
  view.setUint16(32, 2, true);
  view.setUint16(34, 16, true);
  writeString(36, 'data');
  view.setUint32(40, totalSamples * 2, true);

  let offset = 44;
  for (let i = 0; i < totalSamples; i++) {
    const s = Math.max(-1, Math.min(1, samples[i]));
    view.setInt16(offset, s < 0 ? s * 0x8000 : s * 0x7fff, true);
    offset += 2;
  }

  return new Blob([buffer], { type: 'audio/wav' });
}

export async function ensureSeededMediaBlobs(): Promise<void> {
  const seeds: { id: string; bpm: number; cleanliness: number }[] = [
    { id: 'rec-demo-day1', bpm: 85, cleanliness: 3 },
    { id: 'rec-demo-picking', bpm: 112, cleanliness: 5 },
    { id: 'rec-demo-today', bpm: 110, cleanliness: 5 },
  ];

  for (const item of seeds) {
    const existing = await getRecordingBlob(item.id);
    if (!existing) {
      const wavBlob = buildPluckedGuitarWav(item.bpm, item.cleanliness, 6);
      await saveRecordingBlob(item.id, wavBlob);
    }
  }
}
